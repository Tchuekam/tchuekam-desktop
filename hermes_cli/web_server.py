@app.post("/api/providers/validate")
async def validate_provider_credential(body: EnvVarUpdate, request: Request):
    """Live-probe a provider credential before it's saved.

    Returns {ok, reachable, message}. ok=True means the provider accepted the
    key; ok=False + reachable=True means the key is bad (caller should block);
    reachable=False means the network probe couldn't run (caller may save with
    a warning rather than hard-blocking offline users).
    """
    _require_rate_limit(request, "validate", 15, 60.0)
    origin = request.headers.get("origin", "")
    is_public_showcase = _is_public_showcase_mode(request.app)
    is_admin = _has_admin_override(request.headers)
    if not (
        is_public_showcase
        and (_has_valid_session_token(request) or is_admin or _is_allowed_dashboard_origin(origin))
    ):
        _require_token(request)
    import httpx

    key = (body.key or "").strip()
    if is_public_showcase and not is_admin and key not in {"FAL_KEY", "MUAPI_KEY"}:
        raise HTTPException(
            status_code=403,
            detail="Credential validation is disabled for this key in public mode",
        )

    value = (body.value or "").strip()
    if not value:
        return {"ok": False, "reachable": True, "message": "Enter a value first."}

    def _run_probe() -> Dict[str, Any]:
        # Local / custom endpoint: validate connectivity, not auth — any HTTP
        # response (even 401) proves the endpoint is up.
        if key == "OPENAI_BASE_URL":
            parsed_url = urllib.parse.urlparse(value)
            if parsed_url.scheme not in {"http", "https"} or not parsed_url.netloc:
                return {"ok": False, "reachable": False, "message": "Enter a valid http(s) URL."}
            from tools.url_safety import is_safe_url
            if not is_safe_url(value):
                return {"ok": False, "reachable": False, "message": "That endpoint URL is not allowed."}
            url = value.rstrip("/") + "/models"
            try:
                with httpx.Client(timeout=httpx.Timeout(8.0), follow_redirects=False) as client:
                    client.get(url)
                return {"ok": True, "reachable": True, "message": ""}
            except Exception:
                return {"ok": False, "reachable": False, "message": "Could not reach that endpoint."}

        if key == "FAL_KEY":
            # fal.ai has no free "whoami" endpoint. An empty request to a queue
            # endpoint is rejected *before* any job is created or billed: a bad key
            # gets 401/403, a good key gets 400/422 (missing prompt).
            try:
                with httpx.Client(timeout=httpx.Timeout(10.0)) as client:
                    resp = client.post(
                        "https://queue.fal.run/fal-ai/flux/schnell",
                        headers={"Authorization": f"Key {value}", "Content-Type": "application/json"},
                        json={},
                    )
            except Exception:
                return {"ok": False, "reachable": False, "message": "Could not reach fal.ai to verify the key."}
            if resp.status_code in (401, 403):
                return {"ok": False, "reachable": True, "message": "That API key was rejected. Double-check it and try again."}
            if resp.status_code in (400, 422, 429):
                return {"ok": True, "reachable": True, "message": ""}
            return {"ok": False, "reachable": False, "message": f"Could not verify the key (HTTP {resp.status_code})."}

        probe = _CREDENTIAL_PROBES.get(key)
        if not probe:
            # No probe for this provider — can't validate, don't block.
            return {"ok": True, "reachable": False, "message": ""}

        url, auth = probe
        headers = {"Accept": "application/json"}
        params = {}
        if auth == "bearer":
            headers["Authorization"] = f"Bearer {value}"
        elif auth == "x-api-key":
            headers["x-api-key"] = value
        else:
            params["key"] = value

        try:
            with httpx.Client(timeout=httpx.Timeout(10.0)) as client:
                resp = client.get(url, headers=headers, params=params)
        except Exception:
            return {"ok": False, "reachable": False, "message": "Could not reach the provider to verify the key."}

        if resp.status_code in (401, 403):
            return {"ok": False, "reachable": True, "message": "That API key was rejected. Double-check it and try again."}
        if resp.status_code == 429 or resp.is_success:
            # 429 = key is valid but rate-limited; success = valid.
            return {"ok": True, "reachable": True, "message": ""}
        return {"ok": False, "reachable": True, "message": f"Provider returned HTTP {resp.status_code} for this key."}

    return await asyncio.to_thread(_run_probe)


