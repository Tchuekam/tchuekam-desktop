@app.post("/api/audio/transcribe")
async def transcribe_audio_upload(payload: AudioTranscriptionRequest, request: Request):
    _require_rate_limit(request, "audio", 20, 60.0)
    data_url = (payload.data_url or "").strip()
    if not data_url.startswith("data:") or "," not in data_url:
        raise HTTPException(status_code=400, detail="Invalid audio payload")

    header, encoded = data_url.split(",", 1)
    if ";base64" not in header:
        raise HTTPException(
            status_code=400, detail="Audio payload must be base64 encoded"
        )

    if len(encoded) > (_MAX_TRANSCRIPTION_UPLOAD_BYTES * 4 // 3 + 16):
        raise HTTPException(status_code=413, detail="Audio recording is too large")

    mime_type = (
        payload.mime_type or header[5:].split(";", 1)[0] or "audio/webm"
    ).strip()
    normalized_mime_type = mime_type.split(";", 1)[0].lower()
    if not (
        normalized_mime_type.startswith("audio/")
        or normalized_mime_type == "video/webm"
    ):
        raise HTTPException(
            status_code=400, detail="Payload must be an audio recording"
        )

    try:
        audio_bytes = base64.b64decode(encoded, validate=True)
    except (binascii.Error, ValueError):
        raise HTTPException(status_code=400, detail="Audio payload is not valid base64")

    if not audio_bytes:
        raise HTTPException(status_code=400, detail="Audio recording is empty")
    if len(audio_bytes) > _MAX_TRANSCRIPTION_UPLOAD_BYTES:
        raise HTTPException(status_code=413, detail="Audio recording is too large")

    temp_path = ""
    try:
        suffix = _audio_extension_for_mime(mime_type)
        with tempfile.NamedTemporaryFile(
            prefix="hermes-desktop-voice-",
            suffix=suffix,
            delete=False,
        ) as tmp:
            tmp.write(audio_bytes)
            temp_path = tmp.name

        from tools.transcription_tools import transcribe_audio

        def _do_transcribe(path: str):
            try:
                return transcribe_audio(path, allow_fallback=True)
            except TypeError:
                return transcribe_audio(path)

        loop = asyncio.get_running_loop()
        result = await loop.run_in_executor(None, _do_transcribe, temp_path)
    except HTTPException:
        raise
    except Exception:
        _log.exception("Desktop voice transcription failed")
        raise HTTPException(status_code=500, detail="Transcription failed")
    finally:
        if temp_path:
            try:
                os.unlink(temp_path)
            except OSError:
                pass

    if not result.get("success"):
        err_msg = str(result.get("error") or "")
        if "empty transcript" in err_msg.lower():
            return {
                "ok": True,
                "transcript": "",
                "provider": result.get("provider"),
                "filtered": True,
            }
        raise HTTPException(
            status_code=400,
            detail=err_msg or "Transcription failed",
        )

    raw_transcript = str(result.get("transcript") or "").strip()
    try:
        from tools.voice_mode import is_whisper_hallucination, strip_non_speech_audio_tags

        if is_whisper_hallucination(raw_transcript):
            return {
                "ok": True,
                "transcript": "",
                "provider": result.get("provider"),
                "filtered": True,
            }
        raw_transcript = strip_non_speech_audio_tags(raw_transcript)
    except Exception:
        pass

    return {
        "ok": True,
        "transcript": raw_transcript,
        "provider": result.get("provider"),
    }


def _detect_audio_mime_type(audio_bytes: bytes, file_path: str) -> str:
    """Detect actual audio MIME type from magic bytes with file-extension fallback."""
    if len(audio_bytes) >= 12 and audio_bytes[:4] == b"RIFF" and audio_bytes[8:12] == b"WAVE":
        return "audio/wav"
    if len(audio_bytes) >= 4 and audio_bytes[:4] == b"OggS":
        return "audio/ogg"
    if len(audio_bytes) >= 4 and audio_bytes[:4] == b"fLaC":
        return "audio/flac"
    if len(audio_bytes) >= 3 and audio_bytes[:3] == b"ID3":
        return "audio/mpeg"
    if len(audio_bytes) >= 2 and audio_bytes[0] == 0xFF and (audio_bytes[1] & 0xE0) == 0xE0:
        return "audio/mpeg"

    ext = os.path.splitext(file_path)[1].lower()
    return {
        ".mp3": "audio/mpeg",
        ".ogg": "audio/ogg",
        ".opus": "audio/ogg",
        ".wav": "audio/wav",
        ".flac": "audio/flac",
    }.get(ext, "audio/mpeg")


